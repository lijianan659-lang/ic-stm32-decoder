def _norm(s: str) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(s or "").upper())


def lookup_top_marking(raw_input: str) -> dict[str, Any]:
    s = str(raw_input or "").strip().upper()
    if not s:
        return {"input": "", "ok": False, "error": "Empty input", "matches": [], "dateTokens": [], "shareUrl": ""}

    tokens = [t for t in re.split(r"[\s/,;|]+", s) if t]
    full_norm = _norm(s)
    matches: list[dict[str, Any]] = []
    used_idx: set[int] = set()

    for m in VERIFIED_TOP_MARKINGS:
        m_norm = _norm(m["mark"])
        mpn_norm = _norm(m["mpn"])
        matched = False
        reason = ""

        if m_norm == full_norm:
            matched = True
            reason = "Exact top-marking match"
        elif m.get("pat"):
            pat = re.compile(m["pat"])
            hit_any = False
            for ix, tok in enumerate(tokens):
                if pat.match(tok):
                    used_idx.add(ix)
                    hit_any = True
                    break
            if hit_any:
                matched = True
                reason = f"Matches datasheet wildcard pattern ({m['mark']})"
        elif len(tokens) > 1:
            for i, tok in enumerate(tokens):
                if _norm(tok) == m_norm:
                    matched = True
                    used_idx.add(i)
                    reason = f"Matched device-code token {tok}"
                if i + 1 < len(tokens) and _norm(tok + tokens[i + 1]) == m_norm:
                    matched = True
                    used_idx.add(i)
                    used_idx.add(i + 1)
                    reason = f"Matched two-line marking {m['mark']}"

        if not matched and len(full_norm) >= 3 and (full_norm in mpn_norm or (m_norm.startswith(full_norm) and len(full_norm) >= 2)):
            matched = True
            reason = "Reverse MPN-to-marking lookup" if full_norm in mpn_norm else "Prefix marking match"

        if matched:
            item = dict(m)
            item["matchReason"] = reason
            matches.append(item)

    date_tokens: list[str] = []
    for ix, tok in enumerate(tokens):
        if ix in used_idx and len(matches) == 1 and _norm(matches[0]["mark"]) == _norm(tok):
            continue
        if re.match(r"^(?:[0-9]{3,5}|[0-9]{2}\+)$", tok) and (not matches or _norm(matches[0]["mark"]) != tok):
            date_tokens.append(tok)

    return {
        "input": s,
        "ok": len(matches) > 0,
        "matches": matches,
        "dateTokens": date_tokens,
        "shareUrl": f"https://www.partvane.com/tools/ic-marking-decoder/?m={quote(s, safe='')}",
    }
